function listTradingDays(pymByDate, startDate, endDate) {
  const out = [];
  const cur = new Date(`${startDate}T00:00:00.000Z`);
  const stop = new Date(`${endDate}T00:00:00.000Z`);
  while (cur <= stop) {
    const d = cur.toISOString().slice(0, 10);
    if (!isWeekend(d) && pymByDate.has(d)) out.push(d);
    cur.setUTCDate(cur.getUTCDate() + 1);
  }
  return out;
}

// Load EOD cum_dealer_vanna from the SPXW features file for a given day.
// Returns the last finite cum_dealer_vanna in the session, or null if missing.
async function loadSpxwVannaEod(day) {
  const p = defaultFeaturesPath(PROJECT_ROOT, 'SPXW', day);
  if (!fs.existsSync(p)) return null;
  const stream = fs.createReadStream(p).pipe(zlib.createGunzip());
  const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
  let lastVanna = null;
  for await (const line of rl) {
    if (!line) continue;
    const r = JSON.parse(line);
    if (Number.isFinite(r.cum_dealer_vanna)) lastVanna = r.cum_dealer_vanna;
  }
  return lastVanna;
}

async function runVariantForRange({ variant, pymByDate, days }) {
  // Run the strategy day-by-day. Four execution paths:
  //   - default: PYM bias → intraday/overnight SPY trade.
  //   - longOnly: same as default but never take the short side.
  //   - flowWeighted: PYM direction, but check option flow at entry minute and
  //     size 1.5× when flow agrees; entry minute is later (e.g. 10:00 ET) so
  //     cumulative flow has had time to develop. No look-ahead — flow is
  //     measured at the entry minute itself.
  //   - vannaSwing: signal sourced from SPXW EOD cum_dealer_vanna, ranked over
  //     a trailing N-day window. Top quintile → LONG overnight; bottom → SHORT.
  //     PYM bias is not used.
  // Returns:
  //   tradesByDay: per-trade detail with entry/exit (only fully-closed trades)
  //   openPositions: positions that have an entry but the exit minute hasn't been observed yet
  //                  (typically because the session is still in progress or just ended without
  //                   a 15:55 bar in the data — refresh will pick up the close in a later run)
  const tradesByDay = new Map();
  const openPositions = [];
  const featuresCache = new Map();
  async function getFeatures(day) {
    if (!featuresCache.has(day)) featuresCache.set(day, await loadFeatures(day));
    return featuresCache.get(day);
  }

  // Pre-compute SPXW vanna signal series once for the vanna-swing variant.
  let vannaByDay = null;
  let vannaRankedDays = null;
  if (variant.vannaSwing) {
    vannaByDay = new Map();
    for (const day of days) {
      // eslint-disable-next-line no-await-in-loop
      const v = await loadSpxwVannaEod(day);
      if (v != null) vannaByDay.set(day, v);
    }
    vannaRankedDays = Array.from(vannaByDay.keys()).sort();
    process.stdout.write(`  vanna signal coverage: ${vannaByDay.size} days\n`);
  }

  for (let i = 0; i < days.length; i += 1) {
    const day = days[i];

    // === Vanna swing path (signal NOT from PYM) ============================
    if (variant.vannaSwing) {
      if (i === 0) continue; // need prior-day close for entry
      const prevDay = days[i - 1];
      const signalVanna = vannaByDay.get(prevDay);
      if (!Number.isFinite(signalVanna)) continue;
      // Build the trailing window strictly BEFORE prevDay (no look-ahead).
      const window = [];
      for (const d of vannaRankedDays) {
        if (d >= prevDay) break;
        const v = vannaByDay.get(d);
        if (Number.isFinite(v)) window.push(v);
      }
      const lb = variant.vannaLookbackDays || 60;
      const recent = window.slice(-lb);
      if (recent.length < Math.max(20, Math.floor(lb / 2))) continue;
      const sorted = [...recent].sort((a, b) => a - b);
      const qLo = sorted[Math.floor(sorted.length * variant.vannaQuintile)];
      const qHi = sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * (1 - variant.vannaQuintile)))];
      let side = null;
      if (signalVanna >= qHi) side = 'LONG';
      else if (signalVanna <= qLo) side = 'SHORT';
      if (!side) continue;
      // eslint-disable-next-line no-await-in-loop
      const prevRows = await getFeatures(prevDay);
      // eslint-disable-next-line no-await-in-loop
      const todayRows = await getFeatures(day);
      if (!prevRows || !todayRows || prevRows.length === 0 || todayRows.length === 0) continue;
      const entryRow = prevRows.find((r) => r.minute_of_day_et === variant.entryMinuteEt) || prevRows[prevRows.length - 1];
      const exitRow = todayRows.find((r) => r.minute_of_day_et === variant.exitMinuteEt) || todayRows[todayRows.length - 1];
      if (!Number.isFinite(entryRow.spy_close) || !Number.isFinite(exitRow.spy_close)) continue;
      const entryPrice = entryRow.spy_close;
      const exitPrice = exitRow.spy_close;
      const sign = side === 'LONG' ? +1 : -1;
      const gross = sign * variant.leverage * (exitPrice / entryPrice - 1);
      const cost = variant.costBpsRoundTrip / 10_000;
      const net = gross - cost;
      tradesByDay.set(day, {
        date: day,
        entryDay: prevDay,
        entryMode: 'overnight',
        entryMinuteEt: variant.entryMinuteEt,
        exitMinuteEt: variant.exitMinuteEt,
        ticker: side === 'LONG' ? variant.longTicker : variant.shortTicker,
        side,
        leverage: variant.leverage,
        bias: signalVanna,
        entryPrice,
        exitPrice,
        grossReturn: gross,
        cost,
        netReturn: net,
        isWin: net > 0,
        isExtreme: false,
        notes: { vannaQuintile: variant.vannaQuintile, qLo, qHi, signal: signalVanna },
      });
      continue;
    }

    // === PYM-driven paths ===================================================
    const pe = pymByDate.get(day);
    if (!pe || !Number.isFinite(pe.bias)) continue;
    const signal = pe.bias;
    let side = null;
    if (signal >= variant.biasLong) side = 'LONG';
    else if (signal <= variant.biasShort) side = 'SHORT';
    if (!side) continue;
    if (variant.longOnly && side === 'SHORT') continue;
    // Optional skip band: drop trades whose |bias| falls inside [lo, hi).
    // Used to test the "dead zone" finding where mid-conviction buckets underperform.
    if (Array.isArray(variant.biasSkipBand) && variant.biasSkipBand.length === 2) {
      const [lo, hi] = variant.biasSkipBand;
      const ab = Math.abs(signal);
      if (ab >= lo && ab < hi) continue;
    }
    const isExtreme = variant.overnightExtremeBias != null && Math.abs(signal) >= variant.overnightExtremeBias;
    // Per-leg exit minutes (fall back to the legacy single exitMinuteEt).
    // intradayExitMinuteEt: when entryMode === 'intraday' the exit is today at this minute.
    // overnightExitMinuteEt: when entryMode === 'overnight' the exit is today at this minute.
    // overnightEntryMinuteEt: when entryMode === 'overnight' the entry comes from prior day at this minute.
    const intradayExitMin = variant.intradayExitMinuteEt ?? variant.exitMinuteEt;
    const overnightExitMin = variant.overnightExitMinuteEt ?? variant.exitMinuteEt;
    const overnightEntryMin = variant.overnightEntryMinuteEt ?? variant.exitMinuteEt;
    // eslint-disable-next-line no-await-in-loop
    const todayRows = await getFeatures(day);
    if (!todayRows || todayRows.length === 0) continue;
    let entryRow = null; let entryDay = day; let entryMode = 'intraday'; let ticker = side === 'LONG' ? variant.longTicker : variant.shortTicker;
    if (isExtreme && variant.overnightLongTicker) {
      const prev = days[i - 1];
      if (!prev) continue;
      // eslint-disable-next-line no-await-in-loop
      const prevRows = await getFeatures(prev);
      if (!prevRows || prevRows.length === 0) continue;
      const prevExit = prevRows.find((r) => r.minute_of_day_et === overnightEntryMin) || prevRows[prevRows.length - 1];
      if (!Number.isFinite(prevExit.spy_close)) continue;
      entryRow = prevExit; entryDay = prev; entryMode = 'overnight';
      ticker = side === 'LONG' ? variant.overnightLongTicker : variant.overnightShortTicker;
    } else {
      entryRow = todayRows.find((r) => r.minute_of_day_et === variant.entryMinuteEt);
      if (!entryRow || !Number.isFinite(entryRow.spy_open)) continue;
    }
    // Strict match: only treat the exit as final when we actually have the appropriate bar.
    const exitMinForMode = entryMode === 'overnight' ? overnightExitMin : intradayExitMin;
    const exactExitRow = todayRows.find((r) => r.minute_of_day_et === exitMinForMode);
    // No exit bar yet → position is currently OPEN (entry done, exit pending).
    if (!exactExitRow || !Number.isFinite(exactExitRow.spy_close)) {
      const entryPriceOpen = entryMode === 'overnight' ? entryRow.spy_close : entryRow.spy_open;
      openPositions.push({
        signalDate: day,
        entryDate: entryDay,
        entryMinuteEt: entryMode === 'overnight' ? overnightEntryMin : variant.entryMinuteEt,
        expectedExitDate: day,
        expectedExitMinuteEt: exitMinForMode,
        side,
        ticker,
        leverage: variant.leverage,
        bias: pe.bias,
        entryPrice: entryPriceOpen,
        entryMode,
        carryOver: entryMode === 'overnight',
      });
      continue;
    }
    const exitRow = exactExitRow;
    const entryPrice = entryMode === 'overnight' ? entryRow.spy_close : entryRow.spy_open;
    const exitPrice = exitRow.spy_close;

    // Flow-weighted sizing: check cumulative call/put net premium at entry minute.
    // Entry minute is the observation minute — no look-ahead because the feature row
    // is the cumulative state AT that minute (which is precisely what a trader sees).
    let size = 1.0;
    let flowAgrees = null;
    let flowCumNet = null;
    if (variant.flowWeighted && entryMode === 'intraday') {
      const flowRow = entryRow; // observe at entry minute itself
      flowCumNet = (flowRow.cum_call_buy_premium || 0)
        - (flowRow.cum_call_sell_premium || 0)
        - (flowRow.cum_put_buy_premium || 0)
        + (flowRow.cum_put_sell_premium || 0);
      const threshold = variant.flowAgreementThreshold ?? 0;
      flowAgrees = (side === 'LONG' && flowCumNet > threshold)
        || (side === 'SHORT' && flowCumNet < -threshold);
      size = flowAgrees ? (variant.flowAgreeMultiplier ?? 1.5) : (variant.flowDisagreeMultiplier ?? 1.0);
    }

    // Flow-as-filter (hard gate): only trade if option flow agrees with PYM direction.
    // Observation minute is variant.flowFilterMinuteEt (default = entry minute, no look-ahead).
    // If entry is after the observation minute we use that observation row to decide.
    if (variant.flowFilter && entryMode === 'intraday') {
      const obsMinute = variant.flowFilterMinuteEt ?? variant.entryMinuteEt;
      const obsRow = todayRows.find((r) => r.minute_of_day_et === obsMinute);
      if (!obsRow) continue;
      const cumNet = (obsRow.cum_call_buy_premium || 0)
        - (obsRow.cum_call_sell_premium || 0)
        - (obsRow.cum_put_buy_premium || 0)
        + (obsRow.cum_put_sell_premium || 0);
      const threshold = variant.flowAgreementThreshold ?? 0;
      const agrees = (side === 'LONG' && cumNet > threshold)
        || (side === 'SHORT' && cumNet < -threshold);
      if (!agrees) continue; // skip the trade entirely
      flowAgrees = true;
      flowCumNet = cumNet;
    }

    // Bias-proportional sizing: size = min(|bias| / denom, cap). Conviction-aware
    // without adding new signals — extreme convictions get full size, moderate ones scaled down.
    // Floor at biasSizeFloor (default 0) so a tiny non-zero size still trades (no thresholding).
    //
    // biasProportionalSizeMode: 'both' (default) | 'intraday' | 'overnight' — apply selectively.
    // Used to preserve flat 1× sizing on one leg while scaling the other (e.g. keep best-combo's
    // overnight leg flat 1× to avoid amplifying 2025 train-window overnight losers).
    if (variant.biasProportionalSize) {
      const mode = variant.biasProportionalSizeMode || 'both';
      const appliesHere = mode === 'both' || mode === entryMode;
      if (appliesHere) {
        const denom = variant.biasSizeDenom ?? 0.5;
        const cap = variant.biasSizeCap ?? 1.0;
        const floor = variant.biasSizeFloor ?? 0.0;
        size = Math.min(Math.max(Math.abs(signal) / denom, floor), cap);
      }
    }

    const sign = side === 'LONG' ? +1 : -1;
    const gross = sign * variant.leverage * size * (exitPrice / entryPrice - 1);
    const cost = (variant.costBpsRoundTrip / 10_000) * size;
    const net = gross - cost;
    tradesByDay.set(day, {
      date: day,
      entryDay,
      entryDate: entryDay, // alias for UI consistency with wheel
      exitDate: day,
      entryMode,
      entryMinuteEt: entryMode === 'overnight' ? overnightEntryMin : variant.entryMinuteEt,
      exitMinuteEt: exitMinForMode,
      ticker,
      side,
      leverage: variant.leverage,
      size,
      bias: pe.bias,
      entryPrice,
      exitPrice,
      grossReturn: gross,
      cost,
      netReturn: net,
      isWin: net > 0,
      isExtreme,
      carryOver: entryMode === 'overnight', // explicit flag for the UI
      ...(variant.flowWeighted ? { flowAgrees, flowCumNet } : {}),
    });
  }
  return { tradesByDay, openPositions };
}

function maxDrawdown(equityPoints) {
  let peak = equityPoints[0]?.equity || INITIAL_CAPITAL;
  let dd = 0;
  for (const p of equityPoints) {
    peak = Math.max(peak, p.equity);
    if (peak > 0) dd = Math.min(dd, p.equity / peak - 1);
  }
  return dd;
}

function annualizedSharpe(dailyReturns) {
  if (!dailyReturns.length) return 0;
  const m = dailyReturns.reduce((a, x) => a + x, 0) / dailyReturns.length;
  const variance = dailyReturns.reduce((a, x) => a + ((x - m) ** 2), 0) / dailyReturns.length;
  const sd = Math.sqrt(variance);
  if (sd === 0) return 0;
  return (m / sd) * Math.sqrt(252);
}

function buildReportForVariant({ variant, tradesByDay, days, spyByDay, qqqByDay, pymByDate, sourceMeta }) {
  // For each calendar trading day in range, produce a snapshot. Use trade if exists, otherwise cash.
  const equitySeries = [];
  const snapshots = [];
  let equity = INITIAL_CAPITAL;
  let spyEquity = INITIAL_CAPITAL;
  let qqqEquity = INITIAL_CAPITAL;
  const dailyReturns = [];
  let priorSpyClose = null; let priorQqqClose = null;
  let prevHoldings = [];
  for (let i = 0; i < days.length; i += 1) {
    const day = days[i];
    const t = tradesByDay.get(day);
    const todaySpy = spyByDay.get(day);
    const todayQqq = qqqByDay.get(day);
    const dailyReturn = t ? t.netReturn : 0;
    equity = equity * (1 + dailyReturn);
    dailyReturns.push(dailyReturn);
    const spyReturn = todaySpy && priorSpyClose ? (todaySpy / priorSpyClose) - 1 : 0;
    const qqqReturn = todayQqq && priorQqqClose ? (todayQqq / priorQqqClose) - 1 : 0;
    spyEquity *= (1 + spyReturn);
    qqqEquity *= (1 + qqqReturn);
    priorSpyClose = todaySpy ?? priorSpyClose;
    priorQqqClose = todayQqq ?? priorQqqClose;
    const effectiveLev = t ? variant.leverage * (t.size ?? 1) : 0;
    const holdings = t
      ? [{
        ticker: t.ticker,
        weight: t.side === 'LONG' ? +effectiveLev : -effectiveLev,
        weightPct: (t.side === 'LONG' ? +effectiveLev : -effectiveLev) * 100,
        dollars: equity * effectiveLev * (t.side === 'LONG' ? 1 : -1),
      }]
      : [{ ticker: 'CASH', weight: 1, weightPct: 100, dollars: equity }];
    // Turnover: change of weights vs previous
    const prevByTicker = new Map(prevHoldings.map((h) => [h.ticker, h.weight]));
    const newByTicker = new Map(holdings.map((h) => [h.ticker, h.weight]));
    const allTickers = new Set([...prevByTicker.keys(), ...newByTicker.keys()]);
    let turnover = 0;
    for (const tk of allTickers) {
      turnover += Math.abs((newByTicker.get(tk) || 0) - (prevByTicker.get(tk) || 0));
    }
    snapshots.push({
      date: day,
      signalDate: day, // PYM bias was set by prior EOD; we mark signalDate=today since the trade happens today
      rebalanceDate: day,
      execution: t ? (t.entryMode === 'overnight' ? 'pym_gated_overnight' : 'pym_gated_intraday') : 'flat',
      nextDate: days[i + 1] || null,
      equityBeforeNextSession: equity,
      grossExposure: holdings.reduce((s, h) => s + Math.abs(h.weight), 0),
      turnover,
      turnoverPct: turnover * 100,
      estimatedRebalanceCost: t ? t.cost : 0,
      estimatedRebalanceCostPct: (t ? t.cost : 0) * 100,
      holdings,
      topHoldings: holdings.slice(0, 3).map((h) => h.ticker).join(', '),
      benchmarkReturns: { spy: spyReturn, qqq: qqqReturn },
      realized: {
        date: day,
        startEquity: equity / (1 + dailyReturn),
        endEquity: equity,
        grossReturn: t ? t.grossReturn : 0,
        grossReturnPct: (t ? t.grossReturn : 0) * 100,
        netReturn: dailyReturn,
        netReturnPct: dailyReturn * 100,
        costReturn: t ? -t.cost : 0,
        costReturnPct: (t ? -t.cost : 0) * 100,
      },
      trade: t || null,
      pymBias: pymByDate.get(day)?.bias ?? null,
    });
    equitySeries.push({
      date: day,
      signalDate: day,
      equity,
      dailyReturn,
      totalReturn: equity / INITIAL_CAPITAL - 1,
      spyReturn: spyEquity / INITIAL_CAPITAL - 1,
      qqqReturn: qqqEquity / INITIAL_CAPITAL - 1,
    });
    prevHoldings = holdings;
  }

  const trades = Array.from(tradesByDay.values()).sort((a, b) => a.date.localeCompare(b.date));
  const tradeNetReturns = trades.map((t) => t.netReturn);
  const tradeMean = tradeNetReturns.length ? tradeNetReturns.reduce((a, x) => a + x, 0) / tradeNetReturns.length : 0;
  const tradeSd = tradeNetReturns.length > 1
    ? Math.sqrt(tradeNetReturns.reduce((a, x) => a + ((x - tradeMean) ** 2), 0) / tradeNetReturns.length)
    : 0;
  const summary = {
    startDate: days[0] || null,
    endDate: days[days.length - 1] || null,
    initialCapital: INITIAL_CAPITAL,
    finalEquity: equity,
    totalReturn: equity / INITIAL_CAPITAL - 1,
    totalReturnPct: (equity / INITIAL_CAPITAL - 1) * 100,
    cagr: null,
    maxDrawdown: maxDrawdown(equitySeries),
    maxDrawdownPct: maxDrawdown(equitySeries) * 100,
    annualizedVolatility: Math.sqrt(252) * Math.sqrt(dailyReturns.reduce((a, x) => a + (x*x), 0) / Math.max(1, dailyReturns.length)),
    sharpe: annualizedSharpe(dailyReturns),
    sharpePerTrade: tradeSd > 0 ? (tradeMean / tradeSd) * Math.sqrt(252) : 0,
    tradingDays: days.length,
    activeDays: trades.length,
    tradeCount: trades.length,
    longCount: trades.filter((t) => t.side === 'LONG').length,
    shortCount: trades.filter((t) => t.side === 'SHORT').length,
    overnightCount: trades.filter((t) => t.entryMode === 'overnight').length,
    intradayCount: trades.filter((t) => t.entryMode === 'intraday').length,
    winCount: trades.filter((t) => t.isWin).length,
    hitRate: trades.length ? trades.filter((t) => t.isWin).length / trades.length : 0,
    hitRatePct: trades.length ? (trades.filter((t) => t.isWin).length / trades.length) * 100 : 0,
    avgNetReturnBps: trades.length ? (trades.reduce((a, t) => a + t.netReturn, 0) / trades.length) * 10_000 : 0,
    spyReturn: spyEquity / INITIAL_CAPITAL - 1,
    qqqReturn: qqqEquity / INITIAL_CAPITAL - 1,
    todayReturn: equitySeries.at(-1)?.dailyReturn ?? 0,
    todayReturnPct: (equitySeries.at(-1)?.dailyReturn ?? 0) * 100,
    todayDate: equitySeries.at(-1)?.date ?? null,
  };

  return {
    generatedAt: new Date().toISOString(),
    source: {
      provider: 'Massive stock_quotes_1m + OPRA flow + OCC OI overlay',
      pymArtifactPath: sourceMeta.pymArtifactPath,
      featuresDir: sourceMeta.featuresDir,
      generatedAt: sourceMeta.pymGeneratedAt,
    },
    settings: {
      variant: variant.id,
      biasLong: variant.biasLong,
      biasShort: variant.biasShort,
      leverage: variant.leverage,
      entryMinuteEt: variant.entryMinuteEt,
      exitMinuteEt: variant.exitMinuteEt,
      overnightExtremeBias: variant.overnightExtremeBias,
      costBpsRoundTrip: variant.costBpsRoundTrip,
      longTicker: variant.longTicker,
      shortTicker: variant.shortTicker,
      overnightLongTicker: variant.overnightLongTicker,
      overnightShortTicker: variant.overnightShortTicker,
    },
    summary,
    latest: snapshots.at(-1) || null,
    snapshots,
    equitySeries,
    trades,
    skippedDays: [],
  };
}

async function loadBenchmarkCloses(days, symbol) {
  // Extract daily close from per-minute features file for SPY (using exit minute)
  // For QQQ we need a separate run; for simplicity we use SPY features file only and approximate QQQ
  // by reading QQQ features if present.
  const closeByDay = new Map();
  for (const day of days) {
    // eslint-disable-next-line no-await-in-loop
    const p = defaultFeaturesPath(PROJECT_ROOT, symbol, day);
    if (!fs.existsSync(p)) continue;
    // eslint-disable-next-line no-await-in-loop
    const stream = fs.createReadStream(p).pipe(zlib.createGunzip());
    const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
    let lastClose = null;
    // eslint-disable-next-line no-await-in-loop, no-restricted-syntax
    for await (const line of rl) {
      if (!line) continue;
      const r = JSON.parse(line);
      if (Number.isFinite(r.spy_close)) lastClose = r.spy_close;
    }
    if (lastClose != null) closeByDay.set(day, lastClose);
  }
  return closeByDay;
}

function parseArgs(argv) {
  const o = {};
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--start') o.start = argv[++i];
    else if (a === '--end') o.end = argv[++i];
    else if (a === '--pym-artifact') o.pymArtifact = argv[++i];
    else if (a === '--variant') o.variantId = argv[++i];
  }
  return o;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));

  // Preferred: recompute PYM v5 in-memory from the latest Massive EOD daily-bars JSONL
  // (which refresh-eod-inputs.js keeps up-to-date including today). Fall back to the
  // persisted backtest artifact if in-memory recompute fails (e.g. missing bars file).
  let pymByDate;
  let pymSource;
  let pymGeneratedAt = new Date().toISOString();
  if (args.pymArtifact) {
    process.stdout.write(`Using PYM artifact (explicit): ${args.pymArtifact}\n`);
    pymByDate = loadPymHoldings(args.pymArtifact);
    pymSource = args.pymArtifact;
    const obj = JSON.parse(fs.readFileSync(args.pymArtifact, 'utf8'));
    pymGeneratedAt = obj.generatedAt || pymGeneratedAt;
  } else {
    try {
      const { byDate, barsPath } = recomputePymInMemory();
      pymByDate = byDate;
      pymSource = `in-memory:${barsPath}`;
      process.stdout.write(`Recomputed PYM in-memory from ${barsPath} (${pymByDate.size} days)\n`);
    } catch (err) {
      process.stdout.write(`In-memory PYM recompute failed (${err.message}); falling back to latest artifact\n`);
      const fallback = findLatestPymArtifact();
      if (!fallback) {
        process.stderr.write('No PYM source available (in-memory failed and no persisted artifact found).\n');
        process.exit(1);
      }
      pymByDate = loadPymHoldings(fallback);
      pymSource = fallback;
      const obj = JSON.parse(fs.readFileSync(fallback, 'utf8'));
      pymGeneratedAt = obj.generatedAt || pymGeneratedAt;
    }
  }
  const pymArtifactPath = pymSource;
  process.stdout.write(`Loaded ${pymByDate.size} PYM trading days\n`);

  // Date range: from PYM start to either --end or the latest PYM day (or whichever is earlier)
  const allPymDays = Array.from(pymByDate.keys()).sort();
  const startDate = args.start || allPymDays[0];
  const endDate = args.end || allPymDays[allPymDays.length - 1];
  const days = listTradingDays(pymByDate, startDate, endDate);
  process.stdout.write(`Backtest window: ${startDate} → ${endDate} (${days.length} trading days)\n`);

  // Benchmarks
  process.stdout.write('Loading SPY benchmark closes...\n');
  const spyByDay = await loadBenchmarkCloses(days, 'SPY');
  process.stdout.write('Loading QQQ benchmark closes (best-effort)...\n');
  const qqqByDay = await loadBenchmarkCloses(days, 'QQQ');

  const sourceMeta = {
    pymArtifactPath,
    featuresDir: path.relative(PROJECT_ROOT, defaultFeaturesPath(PROJECT_ROOT, 'SPY', '').replace(/\/date=\/?\.jsonl\.gz$/, '')),
    pymGeneratedAt: pymGeneratedAt || null,
  };

  fs.mkdirSync(ARTIFACTS_OUT_DIR, { recursive: true });

  const variantsToRun = args.variantId
    ? VARIANTS.filter((v) => v.id === args.variantId)
    : VARIANTS;

  for (const variant of variantsToRun) {
    process.stdout.write(`\n=== ${variant.id} ===\n`);
    process.stdout.write(`  ${variant.description}\n`);
    // eslint-disable-next-line no-await-in-loop
    const { tradesByDay, openPositions } = await runVariantForRange({ variant, pymByDate, days });
    const report = buildReportForVariant({
      variant, tradesByDay, days, spyByDay, qqqByDay, pymByDate, sourceMeta,
    });
    report.openPositions = openPositions;
    report.metadata = {
      id: variant.id,
      name: variant.name,
      displayName: variant.displayName,
      description: variant.description,
      ruleSummary: variant.ruleSummary,
    };
    const outPath = path.join(ARTIFACTS_OUT_DIR, `${variant.id}-report.json`);
    fs.writeFileSync(outPath, JSON.stringify(report, null, 2));
    process.stdout.write(`  trades=${report.summary.tradeCount} open=${openPositions.length} net=${report.summary.totalReturnPct.toFixed(2)}% Sharpe(day)=${report.summary.sharpe.toFixed(2)} maxDD=${report.summary.maxDrawdownPct.toFixed(2)}% hit=${report.summary.hitRatePct.toFixed(1)}% → ${outPath}\n`);
  }

  process.stdout.write('\nDone.\n');
}

main().catch((err) => { process.stderr.write(`${err.stack || err.message}\n`); process.exit(1); });
