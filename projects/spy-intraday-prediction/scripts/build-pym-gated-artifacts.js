function findLatestPymArtifact() {
  if (!fs.existsSync(DEFAULT_PYM_ARTIFACTS_DIR)) return null;
  const candidates = fs.readdirSync(DEFAULT_PYM_ARTIFACTS_DIR)
    .filter((n) => /^pym-v5-backtest-massive-eod-rsi-wilder-next_close-\d{4}-\d{2}-\d{2}-\d{4}-\d{2}-\d{2}\.json$/.test(n))
    .sort();
  if (!candidates.length) return null;
  return path.join(DEFAULT_PYM_ARTIFACTS_DIR, candidates[candidates.length - 1]);
}

// Compute PYM v5 daily holdings in-memory (mirrors what apps/strategy-service/src/strategies/pym-v5.js
// does at recompute time). This avoids dependence on the persisted backtest JSON, which is only
// regenerated by the legacy CLI `npm run pym-v5:backtest` and stales out between runs.
function recomputePymInMemory() {
  const m = loadPymV5Modules();
  m.loadMassiveEnv();
  const barsPath = process.env.PYM_V5_DAILY_BARS_PATH || m.findLatestMassiveEodBarsPath();
  const scorePath = process.env.PYM_V5_SCORE_PATH || m.defaultScorePath(m.pymConfig);
  if (!barsPath || !fs.existsSync(barsPath)) throw new Error(`missing_pym_daily_bars: ${barsPath}`);
  if (!scorePath || !fs.existsSync(scorePath)) throw new Error(`missing_pym_score: ${scorePath}`);
  const score = JSON.parse(fs.readFileSync(scorePath, 'utf8'));
  const market = m.readDailyBarsJsonl(barsPath);
  const report = m.buildDailyRebalanceReport({
    market,
    score,
    startDate: process.env.PYM_V5_REBALANCE_START || '2025-01-01',
    rsiMode: process.env.PYM_V5_RSI_MODE || 'wilder',
    initialCapital: m.pymConfig.execution?.initialCapital ?? 10_000,
    transactionCostBps: m.pymConfig.execution?.transactionCostBps ?? 1,
    slippageBps: m.pymConfig.execution?.slippageBps ?? 1,
    source: { provider: 'in-memory pym-v5 recompute', barsPath, scorePath },
  });
  // The in-memory report uses snapshots[] where holdings is an array of {ticker, weight, ...}.
  // The persisted backtest JSON uses equityCurve[] keyed by the day the holdings APPLY to
  // (i.e. snap.nextDate, not snap.date). Match that convention so the gated strategy sees the
  // same signal-to-trade-date mapping it had with the persisted artifact:
  //   - snap.date = T            → signal generated at T's close
  //   - snap.nextDate = T+1      → those holdings are in effect during T+1
  //   - so key the bias map by nextDate so byDate.get(T) returns the bias active during day T.
  const byDate = new Map();
  for (const snap of report.snapshots || []) {
    if (!snap.nextDate) continue; // last snapshot's signal would project beyond our data; skip
    const holdingsMap = {};
    for (const h of snap.holdings || []) {
      if (h && h.ticker && Number.isFinite(h.weight)) holdingsMap[h.ticker] = h.weight;
    }
    byDate.set(snap.nextDate, {
      signalDate: snap.date,
      holdings: holdingsMap,
      bias: pymBias(holdingsMap),
      grossReturn: null,
      netReturn: null,
    });
  }
  return { byDate, barsPath, scorePath };
}

function isWeekend(d) {
  const x = new Date(`${d}T00:00:00.000Z`).getUTCDay();
  return x === 0 || x === 6;
}

// Cache the loaded universe config so we can fall back to raw stock_quotes_1m for days
// where features-1m JSONL hasn't been built yet (typically today, before EOD aggregation).
let cachedUniverseConfig = null;
function getUniverseConfig() {
  if (!cachedUniverseConfig) cachedUniverseConfig = loadConfig();
  return cachedUniverseConfig;
}

// Build a synthetic per-minute features row set from raw SPY 1m bars. This is the minimum
// data the PYM-gated variants need (spy_open / spy_close / spy_high / spy_low at the entry
// and exit minutes), enabling today's signal without rebuilding the full features-1m chain.
async function loadFeaturesFromRawStockBars(day) {
  const universe = getUniverseConfig();
  const byMinute = await loadStockBars(universe, day, 'SPY');
  if (byMinute.size === 0) return null;
  const rows = [];
  for (const [minuteMs, bar] of byMinute.entries()) {
    const et = getEtParts(minuteMs);
    if (et.dateEt !== day) continue;
    if (et.minuteOfDayEt < 570 || et.minuteOfDayEt >= 960) continue;
    rows.push({
      minute_ms: minuteMs,
      date_et: et.dateEt,
      minute_of_day_et: et.minuteOfDayEt,
      spy_open: bar.open,
      spy_high: bar.high,
      spy_low: bar.low,
      spy_close: bar.close,
      spy_volume: bar.volume,
      __source: 'raw_stock_bars',
    });
  }
  if (rows.length === 0) return null;
  rows.sort((a, b) => a.minute_ms - b.minute_ms);
  return rows;
}

async function loadFeatures(day) {
  const p = defaultFeaturesPath(PROJECT_ROOT, 'SPY', day);
  if (fs.existsSync(p)) {
    const stream = fs.createReadStream(p).pipe(zlib.createGunzip());
    const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
    const out = [];
    for await (const line of rl) {
      if (!line) continue;
      out.push(JSON.parse(line));
    }
    if (out.length > 0) return out;
  }
  // Fallback: synthesize from raw SPY 1m bars (historical CSV or today's live parquet via DuckDB).
  return loadFeaturesFromRawStockBars(day);
}

